function wrap(
  ticker: string,
  name: string,
  exchange: string,
  years: StatementYear[],
  quote: Omit<CompanyFinancials["quote"], "ticker" | "name" | "exchange">,
  extraWarnings: string[] = [],
): CompanyFinancials {
  const isHk = ticker.endsWith(".HK");
  return {
    quote: { ticker, name, exchange, ...quote },
    years,
    source: "fixture",
    warnings: [
      "Using bundled demo financials. Add FMP_API_KEY for live statements.",
      ...extraWarnings,
    ],
    defaults: {
      riskFreeRate: isHk ? 0.035 : 0.045,
      equityRiskPremium: isHk ? 0.055 : 0.05,
      costOfDebt: 0.065,
      taxRate: isHk ? 0.165 : 0.21,
    },
  };
}


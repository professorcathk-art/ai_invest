function year(
  y: number,
  input: Omit<StatementYear, "year" | "fiscalDate" | "fcf" | "deltaNwc" | "ebitda"> & {
    deltaNwc?: number;
  },
): StatementYear {
  const ebitda = input.ebit + input.da;
  const deltaNwc = input.deltaNwc ?? 0;
  return {
    year: y,
    fiscalDate: `${y}-09-28`,
    ebitda,
    deltaNwc,
    fcf: ufcf({
      ebit: input.ebit,
      taxRate: input.taxRate,
      da: input.da,
      capex: input.capex,
      deltaNwc,
    }),
    ...input,
  };
}

